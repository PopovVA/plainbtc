#!/usr/bin/env python3
"""Regenerate newsletter artefacts from i18n/newsletter.json.

  functions/_lib/nl_strings.js       localized texts for /api/subscribe|confirm|unsubscribe pages
  supabase/newsletter_templates.sql  upsert of the localized confirmation e-mails (public.newsletter_templates)

After changing texts: run this, commit, then apply supabase/newsletter_templates.sql to the Supabase project
(Supabase SQL editor / MCP execute_sql). Safe to re-run.
"""
from __future__ import annotations
import json
from newsletter_lib import ROOT, NL, confirm_email, disclosure_url, home_url

PAGE_KEYS = ["page_confirm_ok_title", "page_confirm_ok_text", "page_confirm_bad_title", "page_confirm_bad_text",
             "page_unsub_ok_title", "page_unsub_ok_text", "page_unsub_bad_title", "page_unsub_bad_text", "page_home",
             "msg_ok", "msg_invalid", "msg_rate", "msg_error"]


def dq(s: str) -> str:
    return "$nl$" + s + "$nl$"


def main():
    js = {c: {k: v[k] for k in PAGE_KEYS} | {"home": home_url(c).replace("https://plainbtc.com", "") or "/"} for c, v in NL.items()}
    out = ROOT / "functions/_lib/nl_strings.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// GENERATED by tools/newsletter_sync.py from i18n/newsletter.json. Do not edit.\n"
                   "export const NL = " + json.dumps(js, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    rows = []
    for c in NL:
        subj, html, text = confirm_email(c)
        rows.append(f"  ({dq(c)}, 'confirm', {dq(subj)}, {dq(html)}, {dq(text)})")
    sql = ("-- GENERATED by tools/newsletter_sync.py. Apply to Supabase after editing i18n/newsletter.json.\n"
           "insert into public.newsletter_templates (lang, kind, subject, html, body_text) values\n" + ",\n".join(rows) +
           "\non conflict (lang, kind) do update set subject = excluded.subject, html = excluded.html, body_text = excluded.body_text;\n")
    (ROOT / "supabase/newsletter_templates.sql").write_text(sql, encoding="utf-8")
    print("wrote functions/_lib/nl_strings.js and supabase/newsletter_templates.sql")


if __name__ == "__main__":
    main()
